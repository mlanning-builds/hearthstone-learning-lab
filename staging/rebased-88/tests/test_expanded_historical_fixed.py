import gzip,json,unittest
from engine.game import Card
from expanded import cards
import test_expanded_historical_death as fixtures
from expanded.historical_death import ROOTS,FIXED_TOKEN_IDS as TOKENS,RULES

class FixedHistoricalTests(unittest.TestCase):
 game=fixtures.HistoricalDeathTests.game
 paid=fixtures.HistoricalDeathTests.paid
 kill=fixtures.HistoricalDeathTests.kill
 @classmethod
 def setUpClass(cls):
  with gzip.open('data/standard/all_cards.json.gz','rt') as f:cls.records={r['id']:r for r in json.load(f)}
 def fixture(self):
  return self.game()
 def test_all_root_paid_plays_and_deaths(self):
  for cid in ROOTS:
   with self.subTest(cid=cid):
    g=self.fixture();m=self.paid(g,cid);self.kill(g,m);g.assert_invariants()
 def test_fixed_children_preserve_frozen_identity_and_stats(self):
  for cid in ('EX1_556','EX1_534','FP1_002','FP1_007','FP1_012'):
   with self.subTest(cid=cid):
    child,count=ROOTS[cid][0][1:];g=self.fixture();m=self.paid(g,cid);self.kill(g,m)
    children=g.players[0].minions;self.assertEqual(len(children),count)
    self.assertEqual({m.card_id for m in children},{child})
    self.assertEqual(len({m.uid for m in children}),count)
    record=self.records[child]
    self.assertEqual([(m.attack,m.health) for m in children],[(record['attack'],record['health'])]*count)
 def test_silence_prevents_fixed_deathrattle(self):
  for cid in ROOTS:
   with self.subTest(cid=cid):
    g=self.fixture();m=self.paid(g,cid);g.players[0].health=20;g._silence(m);self.kill(g,m)
    self.assertFalse(g.players[0].board);self.assertEqual(g.players[0].health,20)
 def test_highmane_and_creeper_respect_one_free_slot(self):
  for cid in ('EX1_534','FP1_002'):
   with self.subTest(cid=cid):
    g=self.fixture();m=self.paid(g,cid)
    for _ in range(6):g._summon(0,'CS2_182')
    self.kill(g,m);self.assertEqual(len(g.players[0].board),7)
    self.assertEqual(sum(x.card_id==ROOTS[cid][0][1] for x in g.players[0].minions),1)
 def test_children_enter_the_vacated_position(self):
  for cid in ('EX1_556','EX1_534','FP1_002','FP1_007','FP1_012'):
   with self.subTest(cid=cid):
    g=self.fixture();left=g._summon(0,'CS2_182');m=g._summon(0,cid);right=g._summon(0,'CS2_182')
    self.kill(g,m);child,count=ROOTS[cid][0][1:]
    self.assertEqual([x.uid for x in g.players[0].board][0],left.uid)
    self.assertEqual([x.uid for x in g.players[0].board][-1],right.uid)
    self.assertEqual([x.card_id for x in g.players[0].board][1:-1],[child]*count)
 def test_slime_keeps_printed_taunt(self):
  g=self.fixture();m=self.paid(g,'FP1_012');self.kill(g,m)
  self.assertIn('TAUNT',g.players[0].minions[0].keywords)
 def test_warbringer_buffs_physical_hand_minions_only(self):
  g=self.fixture();m=self.paid(g,'ULD_183');a=g._add(0,'CS2_182');b=g._add(0,'CORE_CS2_029');uid=a.uid
  self.kill(g,m);self.assertEqual((a.attack_bonus,a.health_bonus,a.uid),(3,3,uid))
  self.assertEqual((b.attack_bonus,b.health_bonus),(0,0))
 def test_khartut_heals_before_reborn_and_on_second_death(self):
  g=self.fixture();g.players[0].health=20;m=self.paid(g,'ULD_208');self.kill(g,m)
  self.assertEqual(g.players[0].health,23);reborn=g.players[0].minions[0]
  self.assertEqual((reborn.card_id,reborn.health),('ULD_208',1));self.assertNotIn('REBORN',reborn.keywords)
  self.kill(g,reborn);self.assertEqual(g.players[0].health,26);self.assertFalse(g.players[0].board)
 def test_khartut_healing_caps_at_maximum(self):
  g=self.fixture();g.players[0].health=29;m=self.paid(g,'ULD_208');self.kill(g,m)
  self.assertEqual(g.players[0].health,30)
 def test_fixed_tokens_replay_their_own_printed_deathrattles(self):
  # Intermediate bodies have literal child recipes of their own. They never
  # inherit the root's recipe simply because they were generated by it.
  descendants={'RLK_650t':['RLK_650t2'],'GIL_616t':['GIL_616t2']*2,
               'GDB_331t1':['GDB_331t2']*2,'GDB_331t2':['GDB_331t3']*2}
  for cid in TOKENS:
   with self.subTest(cid=cid):
    g=self.fixture();m=self.paid(g,cid);self.kill(g,m)
    self.assertEqual([child.card_id for child in g.players[0].minions],descendants.get(cid,[]))
    g.assert_invariants()
